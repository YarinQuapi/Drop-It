export type Copy = typeof en;
export type Lang = "en" | "he";

const dictionaries: Record<Lang, Copy> = { en, he };
const LanguageContext = createContext<{ lang: Lang; t: Copy; setLang: (lang: Lang) => void } | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const initial = navigator.language.toLowerCase().startsWith("he") ? "he" : "en";
  const [lang, setLang] = useState<Lang>(initial);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "he" ? "rtl" : "ltr";
  }, [lang]);
  const value = useMemo(() => ({ lang, t: dictionaries[lang], setLang }), [lang]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("language");
  return value;
}

export type ThemeMode = "system" | "light" | "dark";
export const THEME_MODES: ThemeMode[] = ["system", "light", "dark"];
const THEME_KEY = "dropit_theme";

function readThemeMode(): ThemeMode {
  try {
    const stored = localStorage.getItem(THEME_KEY);
    if (stored === "light" || stored === "dark" || stored === "system") return stored;
  } catch {}
  return "system";
}

function applyThemeMode(mode: ThemeMode) {
  const root = document.documentElement;
  if (mode === "system") root.removeAttribute("data-theme");
  else root.setAttribute("data-theme", mode);
}

const ThemeContext = createContext<{ mode: ThemeMode; setMode: (mode: ThemeMode) => void } | null>(null);

export function ThemeProvider({ children }: { children: ReactNode }) {
  const [mode, setModeState] = useState<ThemeMode>(readThemeMode);
  useEffect(() => {
    applyThemeMode(mode);
  }, [mode]);
  const value = useMemo(() => ({
    mode,
    setMode: (next: ThemeMode) => {
      try {
        localStorage.setItem(THEME_KEY, next);
      } catch {}
      setModeState(next);
    },
  }), [mode]);
  return <ThemeContext.Provider value={value}>{children}</ThemeContext.Provider>;
}

export function useTheme() {
  const value = useContext(ThemeContext);
  if (!value) throw new Error("theme");
  return value;
}
